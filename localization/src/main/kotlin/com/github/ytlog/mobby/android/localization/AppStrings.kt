package com.github.ytlog.mobby.android.localization

/** UI language is independent of Agent protocols and user-authored content. */
enum class AppLanguage(val tag: String, val nativeName: String) {
    CHINESE("zh", "中文"), ENGLISH("en", "English");

    companion object {
        fun fromTag(tag: String?): AppLanguage = values().firstOrNull { it.tag == tag } ?: CHINESE
        @Volatile var current: AppLanguage = CHINESE
    }
}

